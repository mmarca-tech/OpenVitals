            val o = e.asJsonObject
            val times = sampleTimes(o)
            val v = o["v"].asJsonArray
            CyclingPedalingCadenceRecord(
                startTime = instant(o, "start"),
                startZoneOffset = zone(o, "startZoneOffsetSeconds"),
