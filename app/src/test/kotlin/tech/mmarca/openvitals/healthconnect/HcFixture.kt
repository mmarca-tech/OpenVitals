/**
 * The shared fixture, turned back into real Health Connect [Record]s.
 *
 * `golden.json` comes from a real export and is the same file the Dart tier reads.
 * Every record keeps its real `dataOrigin`, `recordingMethod`, `lastModifiedTime` and
 * boundaries, because those are the fields the Flutter port kept losing.
 */
object HcFixture {

    private val root: JsonObject by lazy {
        val stream = HcFixture::class.java.classLoader!!.getResourceAsStream("golden.json")
            ?: error(
                "golden.json is not on the test classpath. It is generated by " +
                    "`python3 tool/health_fixture/build.py` and committed at the repo root; " +
                    "build.gradle adds it as a test resource.",
            )
        Gson().fromJson(stream.reader(), JsonObject::class.java)
    }

    /** Every record in the fixture, ready to insert into a HealthConnectClient. */
    fun allRecords(): List<Record> =
        heartRate() + exercise() + sleep() + speed() + stepsCadence() + power() +
            cyclingCadence() + steps() + distance() + activeCalories() + totalCalories() +
            elevationGained() + hydration() + hrv() + restingHeartRate() +
            basalMetabolicRate()

    /**
     * The instantaneous records: one reading at one time, no span.
     * They sat unparsed for a while, so every corpus test ran without HRV, resting heart rate or BMR.
     */
    fun hrv(): List<HeartRateVariabilityRmssdRecord> =
        array("hrv").map { e ->
            val o = e.asJsonObject
            HeartRateVariabilityRmssdRecord(
                time = instant(o, "time"),
                zoneOffset = zone(o, "zoneOffsetSeconds"),
                heartRateVariabilityMillis = o["v"].asDouble,
                metadata = metadata(o),
            )
        }

    fun restingHeartRate(): List<RestingHeartRateRecord> =
        array("restingHeartRate").map { e ->
            val o = e.asJsonObject
            RestingHeartRateRecord(
                time = instant(o, "time"),
                zoneOffset = zone(o, "zoneOffsetSeconds"),
                beatsPerMinute = o["v"].asDouble.toLong(),
                metadata = metadata(o),
            )
        }

    fun basalMetabolicRate(): List<BasalMetabolicRateRecord> =
        array("basalMetabolicRate").map { e ->
            val o = e.asJsonObject
            BasalMetabolicRateRecord(
                time = instant(o, "time"),
                zoneOffset = zone(o, "zoneOffsetSeconds"),
                basalMetabolicRate = Power.kilocaloriesPerDay(o["v"].asDouble),
                metadata = metadata(o),
            )
        }

    // The swallowing record, and the workout it swallows.

    /** The longest heart-rate record, which hides a workout inside itself. */
    fun swallowingHeartRateRecord(): HeartRateRecord =
        heartRate().maxByOrNull { it.endTime.toEpochMilli() - it.startTime.toEpochMilli() }!!

    /** The exercise session that sits inside it. */
    fun swallowedWorkout(): ExerciseSessionRecord {
        val hr = swallowingHeartRateRecord()
        return exercise().first {
            !it.startTime.isBefore(hr.startTime) && !it.endTime.isAfter(hr.endTime)
        }
    }

    /** The session with a GPS route. */
    fun routeWorkout(): ExerciseSessionRecord {
        val withRoute = array("exercise")
            .map { it.asJsonObject }
            .maxByOrNull { it["route"].asJsonArray.size() }!!
        return exercise().first { it.metadata.id == withRoute["id"].asString }
    }

    // Records.

    fun heartRate(): List<HeartRateRecord> = array("heartRate").map { e ->
        val o = e.asJsonObject
        val times = sampleTimes(o)
        val bpm = o["bpm"].asJsonArray
        HeartRateRecord(
            startTime = instant(o, "start"),
            startZoneOffset = zone(o, "startZoneOffsetSeconds"),
            endTime = instant(o, "end"),
            endZoneOffset = zone(o, "endZoneOffsetSeconds"),
            samples = times.mapIndexed { i, t ->
                HeartRateRecord.Sample(time = t, beatsPerMinute = bpm[i].asLong)
            },
            metadata = metadata(o),
        )
    }

    fun exercise(): List<ExerciseSessionRecord> = array("exercise").map { e ->
        val o = e.asJsonObject
        ExerciseSessionRecord(
            startTime = instant(o, "start"),
            startZoneOffset = zone(o, "startZoneOffsetSeconds"),
            endTime = instant(o, "end"),
            endZoneOffset = zone(o, "endZoneOffsetSeconds"),
            exerciseType = o["exerciseType"].asInt,
            title = o["title"].takeIf { !it.isJsonNull }?.asString,
            notes = o["notes"].takeIf { !it.isJsonNull }?.asString,
            metadata = metadata(o),
            // The GPS track. Distance, pace and the splits are computed from it.
            exerciseRoute = route(o),
        )
    }

    private fun route(o: JsonObject): ExerciseRoute? {
        val points = o["route"].asJsonArray
        if (points.isEmpty()) return null
        return ExerciseRoute(
            points.map { p ->
                val point = p.asJsonObject
                ExerciseRoute.Location(
                    time = Instant.ofEpochMilli(point["t"].asLong),
                    latitude = point["lat"].asDouble,
                    longitude = point["lon"].asDouble,
                    altitude = point["alt"].takeIf { !it.isJsonNull }
                        ?.let { Length.meters(it.asDouble) },
                    horizontalAccuracy = point["acc"].takeIf { !it.isJsonNull }
                        ?.let { Length.meters(it.asDouble) },
                )
            },
        )
    }

    /** The hydration entries, the one record type this app wrote in the corpus. */
    fun hydration(): List<HydrationRecord> = array("hydration").map { e ->
        val o = e.asJsonObject
        HydrationRecord(
            startTime = instant(o, "start"),
            startZoneOffset = zone(o, "startZoneOffsetSeconds"),
            endTime = instant(o, "end"),
            endZoneOffset = zone(o, "endZoneOffsetSeconds"),
            volume = Volume.liters(o["v"].asDouble),
            metadata = metadata(o),
        )
    }

    fun sleep(): List<SleepSessionRecord> = array("sleep").map { e ->
        val o = e.asJsonObject
        SleepSessionRecord(
            startTime = instant(o, "start"),
            startZoneOffset = zone(o, "startZoneOffsetSeconds"),
            endTime = instant(o, "end"),
            endZoneOffset = zone(o, "endZoneOffsetSeconds"),
            title = o["title"].takeIf { !it.isJsonNull }?.asString,
            notes = o["notes"].takeIf { !it.isJsonNull }?.asString,
            stages = o["stages"].asJsonArray.map { s ->
                val st = s.asJsonObject
                SleepSessionRecord.Stage(
                    startTime = Instant.ofEpochMilli(st["start"].asLong),
                    endTime = Instant.ofEpochMilli(st["end"].asLong),
                    stage = st["type"].asInt,
                )
            },
            metadata = metadata(o),
        )
    }

    fun speed(): List<SpeedRecord> = array("speed").map { e ->
        val o = e.asJsonObject
        val times = sampleTimes(o)
        val v = o["v"].asJsonArray
        SpeedRecord(
            startTime = instant(o, "start"),
            startZoneOffset = zone(o, "startZoneOffsetSeconds"),
            endTime = instant(o, "end"),
            endZoneOffset = zone(o, "endZoneOffsetSeconds"),
            samples = times.mapIndexed { i, t ->
                SpeedRecord.Sample(time = t, speed = Velocity.metersPerSecond(v[i].asDouble))
